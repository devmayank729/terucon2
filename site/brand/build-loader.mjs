#!/usr/bin/env node
// Keeps the loader's four copies of one thing in step:
//   site/brand/loader.css    the loader's style sheet (the one you edit; also served at /brand/loader.css for pages that have no
//                            loader of their own: transition.js links it)
//   site/brand/loader.html   its first <style> block is a copy of loader.css (inline, so the loader paints with the first bytes of a
//                            page); the markup in it is the one you edit
//   site/brand/transition.js its MARKUP constant is a copy of the loader's markup (between the loader-markup markers)
//   site/brand/loader.js     GENERATED whole (never edited): the loader for the hand-written pages (Finder, Inspiration, the project form,
//                            sign-in, account, admin, coming soon). They load /brand/loader.css and this script first in <head>; it puts the
//                            same loader on screen at once (the markup, appended to <html> like the site chrome) and runs the loader's own
//                            script from loader.html, then lets the loader go when the page is ready (see PAGE_READY below). The four built
//                            pages carry the loader inline instead, and a page that has one already is left alone.
//
//   node site/brand/build-loader.mjs           rewrite loader.html's style block, transition.js's MARKUP and loader.js
//   node site/brand/build-loader.mjs --check   exit 1 (and say what) when any is out of date; writes nothing
//
// tests/js/brand-loader.test.js runs the same check, so a change to loader.css or the markup that skips this fails `npm test`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (name) => fs.readFileSync(path.join(here, name), 'utf8');

/** The element #tc-loader as one string: from its opening tag up to the script block, source lines trimmed and joined. */
export function markupOf(html) {
  const start = html.indexOf('<div id="tc-loader"');
  const end = html.indexOf('<script>', start);
  if (start === -1 || end === -1) throw new Error('loader.html: markup not found');
  return html
    .slice(start, end)
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('');
}

/** The loader's own script (the one <script> block of loader.html), without the tags. */
export function scriptOf(html) {
  const open = html.indexOf('<script>');
  const close = html.indexOf('</script>', open);
  if (open === -1 || close === -1) throw new Error('loader.html: script block not found');
  return html.slice(open + '<script>'.length, close).trim();
}

/**
 * When a hand-written page's loader may go: the document is parsed, the fonts it asked for have arrived (or 1.2 s have passed: a font
 * is never a reason to hold a page back), and two frames have been painted. The built pages decide this in tools/build-dist.js
 * (READY_SCRIPT, the page runtime's first commit); these pages are plain HTML, so this is their equivalent.
 */
const PAGE_READY = `
  var release = function () { try { if (w.TeruconLoader) w.TeruconLoader.done(); } catch (e) {} };
  var paint = function () { w.requestAnimationFrame(function () { w.requestAnimationFrame(release); }); };
  var settle = function () {
    var gone = false;
    var go = function () { if (gone) return; gone = true; paint(); };
    if (d.fonts && d.fonts.ready && typeof d.fonts.ready.then === 'function') d.fonts.ready.then(go, go);
    w.setTimeout(go, 1200);
    if (!d.fonts || !d.fonts.ready) go();
  };
  if (d.readyState === 'loading') d.addEventListener('DOMContentLoaded', settle);
  else settle();`;

/** loader.js: see the header of this file. */
export function loaderJsOf(markup, script) {
  const body = script.split('\n').map((line) => (line ? '  ' + line : line)).join('\n');
  return [
    '/* GENERATED by site/brand/build-loader.mjs from loader.html: do not edit it, edit loader.css / loader.html and run',
    '   node site/brand/build-loader.mjs. The Terucon loader for the hand-written pages: load /brand/loader.css and then this file, first in',
    '   <head> (a render-blocking sheet and a small synchronous script, so the loader is the first thing painted, like the site chrome). It puts',
    '   the loader on screen, runs its script and lets it go when the page is ready: the document is parsed, the fonts have arrived (at most',
    '   1.2 s) and two frames are painted. The built pages carry the loader inline; a page that has one is left alone. */',
    '(function () {',
    '  var w = window;',
    '  var d = document;',
    "  if (w.TeruconLoader || d.getElementById('tc-loader') || !d.documentElement) return;",
    `  var MARKUP = ${JSON.stringify(markup)};`,
    "  var holder = d.createElement('div');",
    '  holder.innerHTML = MARKUP;',
    '  var node = holder.firstElementChild;',
    '  if (!node) return;',
    '  d.documentElement.appendChild(node); // a child of <html>, like the site chrome: it is there before <body> is',
    '',
    body,
    PAGE_READY,
    '})();',
    '',
  ].join('\n');
}

/** What the files should contain: { loaderHtml, transitionJs, loaderJs, markup }. */
export function build(dir = here) {
  const get = (name) => fs.readFileSync(path.join(dir, name), 'utf8');
  const css = get('loader.css').replace(/\s+$/, '');
  let html = get('loader.html');
  // the first <style> block holds the loader's sheet; the one inside <noscript> is separate and never touched
  const styleRe = /<style>[\s\S]*?<\/style>/;
  if (!styleRe.test(html)) throw new Error('loader.html has no <style> block');
  html = html.replace(styleRe, () => `<style>\n${css}\n</style>`);
  const markup = markupOf(html);
  let js = get('transition.js');
  const markRe = /\/\*loader-markup:start\*\/[\s\S]*?\/\*loader-markup:end\*\//;
  if (!markRe.test(js)) throw new Error('transition.js has no loader-markup markers');
  js = js.replace(markRe, () => `/*loader-markup:start*/\n  var MARKUP = ${JSON.stringify(markup)};\n  /*loader-markup:end*/`);
  return { loaderHtml: html, transitionJs: js, loaderJs: loaderJsOf(markup, scriptOf(html)), markup };
}

/** Names of the files that are not what build() says they should be. */
export function stale(dir = here) {
  const get = (name) => fs.readFileSync(path.join(dir, name), 'utf8');
  const { loaderHtml, transitionJs, loaderJs } = build(dir);
  const out = [];
  if (loaderHtml !== get('loader.html')) out.push('loader.html (its <style> block is not loader.css)');
  if (transitionJs !== get('transition.js')) out.push('transition.js (MARKUP is not the loader markup)');
  let have = null;
  try { have = get('loader.js'); } catch { /* missing */ }
  if (loaderJs !== have) out.push('loader.js (it is not what loader.html generates)');
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = stale();
  if (process.argv.includes('--check')) {
    if (out.length) {
      console.error(`out of date: ${out.join('; ')}\nrun: node site/brand/build-loader.mjs`);
      process.exit(1);
    }
    console.log('loader.css, loader.html, transition.js and loader.js are in step.');
  } else {
    const { loaderHtml, transitionJs, loaderJs } = build();
    fs.writeFileSync(path.join(here, 'loader.html'), loaderHtml);
    fs.writeFileSync(path.join(here, 'transition.js'), transitionJs);
    fs.writeFileSync(path.join(here, 'loader.js'), loaderJs);
    console.log(out.length ? `rewrote: ${out.join('; ')}` : 'already in step.');
  }
}
